class HeadlessAmazonScanner(QObject):
    finished = Signal(list)
    progress = Signal(str)
    error = Signal(str)

    def __init__(self, parent=None):
        super().__init__(parent)
        from dialogs.login_browser_dialog import get_amazon_profile
        self.profile = get_amazon_profile()
        
        # Attach to the main window as parent to inherit its native window handle.
        # This guarantees that the Chromium process is spawned and JavaScript execution is never throttled.
        main_win = parent.mw if parent and hasattr(parent, 'mw') else None
        self.browser = QWebEngineView(main_win)
        self.browser.hide()
        
        self.page = SilentWebEnginePage(self.profile, self.browser)
        self.browser.setPage(self.page)
        
        self.poll_timer = QTimer(self)
        self.poll_timer.setInterval(1000)
        self.poll_timer.timeout.connect(self.poll_js_state)
        
        self.region_code = "US"
        self.csrf_not_found_ticks = 0

    def start_scan(self, region_code="US"):
        self.region_code = region_code
        self.csrf_not_found_ticks = 0
        self.vgv_scan_routed = False
        from backend.amazon.login_amazon import get_region_config
        config = get_region_config(region_code)
        
        url = f"https://{config.lunaDomain}/"
        self.browser.load(QUrl(url))
        # WHY: Start the 1-second polling timer so poll_js_state checks page states and executes the scan.
        self.poll_timer.start()

    def stop_scan(self):
        self.poll_timer.stop()
        self.browser.triggerAction(QWebEnginePage.WebAction.Stop)

    def clean_up(self):
        self.poll_timer.stop()
        if hasattr(self, 'browser') and self.browser is not None:
            self.browser.stop()
            self.browser.setParent(None)
            self.browser.deleteLater()
            self.browser = None
        if hasattr(self, 'page') and self.page is not None:
            self.page.setParent(None)
            self.page.deleteLater()
            self.page = None

