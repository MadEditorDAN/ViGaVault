    def run_remaining_full_scan(self, do_galaxy, do_local, do_gog_web, do_epic, do_steam, do_amazon, amazon_claims, do_dl_images, target_folders, amazon_stats=None):
        self.full_scan_worker = FullScanWorker(
            do_galaxy=do_galaxy,
            do_local=do_local,
            do_gog_web=do_gog_web,
            do_epic=do_epic,
            do_steam=do_steam,
            do_amazon=do_amazon,
            amazon_claims=amazon_claims,
            amazon_stats=amazon_stats, # WHY: Pass the accumulated Amazon stats to the background worker thread.
            do_download_images=do_dl_images,
            target_folders=target_folders,
            parent=self
        )
        self.full_scan_worker.finished.connect(self.finish_full_scan)
        self.full_scan_worker.renames_ready_signal.connect(self.handle_proposed_renames)
        self.full_scan_worker.start()

    def handle_proposed_renames(self, proposed_renames):
        from dialogs.rename_confirmation_dialog import RenameConfirmationDialog
        dlg = RenameConfirmationDialog(proposed_renames, self.mw)
        if dlg.exec():
            approved = dlg.get_approved_renames()
            if approved:
                self.mw.game_operations_controller.execute_batch_renames(approved)

    def stop_full_scan(self):
        if hasattr(self, 'amazon_scanner') and self.amazon_scanner:
            self.amazon_scanner.clean_up()
            self.amazon_scanner.deleteLater()
            self.amazon_scanner = None

        if self.mw.full_scan_in_progress:
            logging.info(f"{' Full Scan interrupted by user ':-^80}")
            if hasattr(self, 'full_scan_worker') and self.full_scan_worker:
                self.full_scan_worker.requestInterruption()
            else:
                self.finish_full_scan()
                self.mw.sidebar.scan_panel.hide()
